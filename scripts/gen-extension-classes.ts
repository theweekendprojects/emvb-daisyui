// Regenerates src/extension/classes.ts from the catalog. Run: bun run gen:classes
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { collectClasses } from "../src/extension/collect-classes.ts";

const out = join(dirname(fileURLToPath(import.meta.url)), "../src/extension/classes.ts");
const classes = collectClasses();
const body = classes.map((name) => `  "${name}",`).join("\n");
writeFileSync(
  out,
  `// Generated by scripts/gen-extension-classes.ts from the catalog. Do not edit by hand.\nexport const CLASSES_FOR_EXTENSION: readonly string[] = [\n${body}\n];\n`,
);
console.log(`wrote ${classes.length} class tokens to ${out}`);
